<?php
declare(strict_types=1);

namespace MyPHP;

use ReflectionClass;
use ReflectionMethod;
use ReflectionNamedType;
use ReflectionType;
use ReflectionUnionType;

/**
 * Writes the TypeScript client for the bound services and declared events,
 * as `mygo generate` does: one const per service with a typed method per
 * public PHP method, interfaces for the classes they take and return.
 * Array shapes come from PHPDoc (`Note[]`, `list<Note>`, `array<string, int>`);
 * a bare `array` is `unknown`.
 */
final class TypeScript
{
    /** @var array<string, string> interface name => declaration, in order of discovery */
    private static array $interfaces = [];
    /** @var array<string, true> the types of myphp-runtime the client uses, which it imports */
    private static array $imported = [];
    /** The npm package of the page runtime, which generated clients import (mygo's RuntimePackage). */
    public const RUNTIME_PACKAGE = 'myphp-runtime';
    /** The namespace the PHPDoc types read now are relative to: that of the method's class, or of the class whose properties they type. */
    private static string $ns = '';
    private const BUILTIN = ['int', 'float', 'string', 'bool', 'true', 'false', 'void', 'null', 'array', 'mixed', 'object', 'self', 'static', 'iterable', 'callable'];
    public static function generate(): string
    {
        self::$interfaces = [];
        self::$imported = [];
        $services = '';
        foreach (Ipc::services() as $name => $svc) {
            if ($svc['plugin']) {
                continue; // a plugin's page side is its own client
            }
            $methods = '';
            foreach ($svc['methods'] as $mname => $m) {
                self::$ns = $m->getDeclaringClass()->getNamespaceName();
                $params = [];
                $names = [];
                foreach ($m->getParameters() as $p) {
                    $pt = $p->getType();
                    if ($pt instanceof ReflectionNamedType && $pt->getName() === CallContext::class) {
                        continue; // the call's, not the page's
                    }
                    $doc = self::docTag($m, 'param', $p->getName());
                    $params[] = $p->getName() . ($p->isOptional() ? '?' : '') . ': ' . self::type($p->getType(), $doc);
                    $names[] = $p->getName();
                }
                $retDoc = self::docTag($m, 'return');
                $rt = $m->getReturnType();
                if ($rt instanceof ReflectionNamedType && $rt->getName() === \Generator::class) {
                    // A streaming method: the reply is the generator's return value, @return names it (not Generator<...>).
                    $ret = $retDoc === null || str_starts_with($retDoc, 'Generator') || str_starts_with($retDoc, '\\Generator') ? 'void' : self::docType($retDoc);
                } else {
                    $ret = self::type($rt, $retDoc);
                }
                $methods .= self::tsdoc($m->getDocComment(), '  ')
                    . "  $mname(" . implode(', ', $params) . "): Promise<$ret> {\n"
                    . "    return call(\"$name.$mname\"" . ($names ? ', ' . implode(', ', $names) : '') . ");\n  },\n";
            }
            $services .= "\n" . self::tsdoc($svc['doc'], '') . "export const $name = {\n$methods} as const;\n";
        }
        $events = '';
        self::$ns = ''; // the events' payload types are named in full (Stats::class)
        foreach (Event::declared() as $ename => $ptype) {
            $t = self::docType($ptype);
            $events .= '  ' . self::eventKey($ename) . ': event<' . $t . '>(' . json_encode($ename) . "),\n";
        }
        // The runtime comes from the myphp-runtime package, as mygo's clients' from mygo-runtime.
        $imports = [];
        if ($services !== '') {
            $imports[] = 'call';
        }
        if ($events !== '') {
            $imports[] = 'event';
        }
        $used = array_keys(self::$imported);
        sort($used);
        foreach ($used as $type) {
            $imports[] = "type $type";
        }
        $out = "// Code generated by `myphp generate`. DO NOT EDIT.\n\n";
        if ($imports !== []) {
            $out .= 'import { ' . implode(', ', $imports) . ' } from "' . self::RUNTIME_PACKAGE . "\";\n";
        }
        if (self::$interfaces !== []) {
            $names = array_keys(self::$interfaces);
            sort($names, SORT_STRING);
            $out .= "\n// ---- Types ----\n\n";
            foreach ($names as $n) {
                $out .= self::$interfaces[$n] . "\n";
            }
        }
        if ($services !== '') {
            $out .= (self::$interfaces === [] ? "\n" : '') . "// ---- Services ----\n" . $services . "\n";
        }
        if ($events !== '') {
            $out .= "// ---- Events ----\n\n/** Events sent by the PHP side. Subscribe with `events.name.on(listener)`. */\nexport const events = {\n$events} as const;\n";
        }
        $out = rtrim($out, "\n") . "\n";
        return $out;
    }

    private static function type(?ReflectionType $t, ?string $doc): string
    {
        if ($doc !== null && $doc !== '') {
            return self::docType($doc);
        }
        if ($t === null) {
            return 'unknown';
        }
        if ($t instanceof ReflectionUnionType) {
            return implode(' | ', array_map(fn($x) => self::type($x, null), $t->getTypes()));
        }
        if (!$t instanceof ReflectionNamedType) {
            return 'unknown';
        }
        $ts = self::named($t->getName());
        return $t->allowsNull() && $ts !== 'null' && $ts !== 'void' && $ts !== 'unknown' ? "$ts | null" : $ts;
    }

    private static function named(string $php): string
    {
        return match ($php) {
            'int', 'float' => 'number',
            'string' => 'string',
            'bool', 'true', 'false' => 'boolean',
            'void' => 'void',
            'null' => 'null',
            'array', 'mixed', 'object' => 'unknown',
            Channel::class => self::import('Channel') . '<unknown>',
            ThemePreferences::class => self::import('ThemePreferences'), // its JSON is the runtime's type
            'self', 'static' => 'unknown',
            default => enum_exists($php) ? self::enumType($php) : self::interface($php),
        };
    }

    /** A type of myphp-runtime, which the client imports. */
    private static function import(string $type): string
    {
        self::$imported[$type] = true;
        return $type;
    }

    /** Declares a backed enum (once) as the union of its values, which is what JSON carries of it, as mygo's typed constants; a pure enum, which JSON has nothing of, is unknown. */
    private static function enumType(string $class): string
    {
        $rc = new \ReflectionEnum($class);
        if (!$rc->isBacked()) {
            return 'unknown';
        }
        $name = $rc->getShortName();
        if (!isset(self::$interfaces[$name])) {
            $values = array_map(fn(\ReflectionEnumBackedCase $c): string => json_encode($c->getBackingValue(), JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES), $rc->getCases());
            self::$interfaces[$name] = self::tsdoc($rc->getDocComment(), '') . "export type $name = " . ($values === [] ? 'never' : implode(' | ', $values)) . ";\n";
        }
        return $name;
    }

    /** A PHPDoc type such as `Note[]`, `list<Note>`, `array<string, int>`, `?Note`, `Note|null`. */
    private static function docType(string $doc): string
    {
        $doc = trim($doc);
        if (str_starts_with($doc, '?')) {
            return self::docType(substr($doc, 1)) . ' | null';
        }
        if (str_contains($doc, '|')) {
            return implode(' | ', array_map(self::docType(...), explode('|', $doc)));
        }
        if (str_ends_with($doc, '[]')) {
            return self::docType(substr($doc, 0, -2)) . '[]';
        }
        if (preg_match('/^(\\\\?MyPHP\\\\)?Channel<\s*(.+)\s*>$/', $doc, $m)) {
            return self::import('Channel') . '<' . self::docType($m[2]) . '>';
        }
        if (preg_match('/^(list|array|iterable)<\s*([^,>]+)\s*>$/', $doc, $m)) {
            return self::docType($m[2]) . '[]';
        }
        if (preg_match('/^array<\s*([^,]+)\s*,\s*(.+)>$/', $doc, $m)) {
            return 'Record<' . self::docType($m[1]) . ', ' . self::docType($m[2]) . '>';
        }
        $name = ltrim($doc, '\\');
        return self::named($name !== $doc || in_array(strtolower($name), self::BUILTIN, true) ? $name : self::resolve($name));
    }

    /** A class named in a PHPDoc type, as PHP reads it: in the namespace of the code it documents, else global; a class loaded is taken before one autoloaded. */
    private static function resolve(string $name): string
    {
        if (self::$ns === '') {
            return $name;
        }
        $local = self::$ns . '\\' . $name;
        if (class_exists($local, false) || enum_exists($local, false)) {
            return $local;
        }
        if (class_exists($name, false) || enum_exists($name, false)) {
            return $name;
        }
        return class_exists($local) ? $local : $name;
    }

    /** Declares the interface for a class (once) and returns its name. */
    private static function interface(string $class): string
    {
        if (!class_exists($class)) {
            return 'unknown';
        }
        $rc = new ReflectionClass($class);
        $name = $rc->getShortName();
        if (!isset(self::$interfaces[$name])) {
            self::$interfaces[$name] = ''; // claims the name while properties recurse
            $saved = self::$ns;
            self::$ns = $rc->getNamespaceName();
            $props = '';
            foreach ($rc->getProperties(\ReflectionProperty::IS_PUBLIC) as $p) {
                if ($p->isStatic()) {
                    continue;
                }
                $doc = null;
                if (preg_match('/@var\s+(\S+)/', (string)$p->getDocComment(), $m)) {
                    $doc = $m[1];
                }
                $props .= self::tsdoc($p->getDocComment(), '  ') . '  ' . $p->getName() . ': ' . self::type($p->getType(), $doc) . ";\n";
            }
            self::$ns = $saved;
            self::$interfaces[$name] = self::tsdoc($rc->getDocComment(), '') . "export interface $name {\n$props}\n";
        }
        return $name;
    }

    private static function docTag(ReflectionMethod $m, string $tag, ?string $param = null): ?string
    {
        $doc = (string)$m->getDocComment();
        $re = $param === null ? "/@$tag\\s+(\\S+)/" : "/@$tag\\s+(\\S+)\\s+\\$$param\\b/";
        return preg_match($re, $doc, $x) ? $x[1] : null;
    }

    /** The description lines of a docblock as TSDoc, or nothing. */
    private static function tsdoc(string|false $doc, string $indent): string
    {
        if ($doc === false || $doc === '') {
            return '';
        }
        $lines = [];
        foreach (preg_split('/\R/', trim($doc, "/* \t\n")) as $line) {
            $line = trim(ltrim(trim($line), '*'));
            if ($line === '' || str_starts_with($line, '@')) {
                if ($line !== '' || $lines === []) {
                    continue;
                }
            }
            $lines[] = $line;
        }
        if ($lines === []) {
            return '';
        }
        return count($lines) === 1
            ? "$indent/** {$lines[0]} */\n"
            : "$indent/**\n" . implode('', array_map(fn($l) => "$indent * $l\n", $lines)) . "$indent */\n";
    }

    /** The key of an event in the client's `events`, as mygo's eventKey: its name camel-cased at - _ : . space and /, "todos:changed" todosChanged; the name quoted where that is no identifier. */
    private static function eventKey(string $name): string
    {
        $key = ''; $upper = false;
        foreach (mb_str_split($name) as $i => $ch) {
            if (strpbrk($ch, "-_:. /") !== false) { $upper = $key !== ''; continue; }
            if ($upper) { $ch = mb_strtoupper($ch); $upper = false; } elseif ($i === 0) { $ch = mb_strtolower($ch); }
            $key .= $ch;
        }
        return preg_match('/^[\p{L}_$][\p{L}\p{N}_$]*$/u', $key) ? $key : (string)json_encode($name);
    }
}
