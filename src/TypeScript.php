<?php
declare(strict_types=1);

namespace MyPHP;

use ReflectionClass;
use ReflectionMethod;
use ReflectionNamedType;
use ReflectionType;
use ReflectionUnionType;

/**
 * Writes the TypeScript client for the bound services and declared events,
 * as `mygo generate` does: one const per service with a typed method per
 * public PHP method, interfaces for the classes they take and return.
 * Array shapes come from PHPDoc (`Note[]`, `list<Note>`, `array<string, int>`);
 * a bare `array` is `unknown`.
 */
final class TypeScript
{
    /** @var array<string, string> interface name => declaration, in order of discovery */
    private static array $interfaces = [];
    public static function generate(): string
    {
        self::$interfaces = [];
        $services = '';
        foreach (Ipc::services() as $name => $svc) {
            if ($svc['plugin']) {
                continue; // a plugin's page side is its own client
            }
            $methods = '';
            foreach ($svc['methods'] as $mname => $m) {
                $params = [];
                $names = [];
                foreach ($m->getParameters() as $p) {
                    $pt = $p->getType();
                    if ($pt instanceof ReflectionNamedType && $pt->getName() === CallContext::class) {
                        continue; // the call's, not the page's
                    }
                    $doc = self::docTag($m, 'param', $p->getName());
                    $params[] = $p->getName() . ($p->isOptional() ? '?' : '') . ': ' . self::type($p->getType(), $doc);
                    $names[] = $p->getName();
                }
                $retDoc = self::docTag($m, 'return');
                $rt = $m->getReturnType();
                if ($rt instanceof ReflectionNamedType && $rt->getName() === \Generator::class) {
                    // A streaming method: the reply is the generator's return value, @return names it (not Generator<...>).
                    $ret = $retDoc === null || str_starts_with($retDoc, 'Generator') || str_starts_with($retDoc, '\\Generator') ? 'void' : self::docType($retDoc);
                } else {
                    $ret = self::type($rt, $retDoc);
                }
                $methods .= self::tsdoc($m->getDocComment(), '  ')
                    . "  $mname(" . implode(', ', $params) . "): Promise<$ret> {\n"
                    . "    return call(\"$name.$mname\"" . ($names ? ', ' . implode(', ', $names) : '') . ");\n  },\n";
            }
            $services .= "\n" . self::tsdoc($svc['doc'], '') . "export const $name = {\n$methods} as const;\n";
        }
        $events = '';
        foreach (Event::declared() as $ename => $ptype) {
            $t = self::docType($ptype);
            $events .= "  $ename: (fn: (payload: $t) => void) => on(\"$ename\", fn as (payload: unknown) => void),\n";
        }
        $out = "// Code generated by MyPHP (MYPHP_GENERATE). DO NOT EDIT.\n\n"
            . "declare global {\n  interface Window {\n    myphp: {\n"
            . "      call<T = unknown>(method: string, ...args: unknown[]): Promise<T>;\n"
            . "      on(name: string, fn: (payload: unknown) => void): () => void;\n"
            . "      once(name: string, fn: (payload: unknown) => void): () => void;\n"
            . "      readonly preferences: { accent: string | null; reduceMotion: boolean; reduceTransparency: boolean; highContrast: boolean; textScale: number };\n"
            . "      readonly locale: string;\n      readonly dir: \"ltr\" | \"rtl\";\n"
            . "      isCallError(e: unknown): boolean;\n      platform: string;\n      windowId: number;\n      version: string;\n"
            . "      Channel: new <T = unknown>() => Channel<T>;\n"
            . "      window: { minimize(): Promise<void>; maximize(): Promise<void>; unmaximize(): Promise<void>; toggleMaximize(): Promise<void>;"
            . " isMaximized(): Promise<boolean>; toggleFullScreen(): Promise<void>; close(): Promise<void>; setTitle(title: string): Promise<void> };\n"
            . "    };\n  }\n}\n\n"
            . "/** A stream of values from a PHP method: pass one for a Channel parameter, then iterate it or set onmessage. */\n"
            . "export interface Channel<T> {\n  onmessage: ((value: T) => void) | null;\n  onclose: (() => void) | null;\n  readonly closed: boolean;\n"
            . "  /** Stops the method's sending; breaking out of a for-await loop does the same. */\n  close(): void;\n  [Symbol.asyncIterator](): AsyncIterator<T>;\n}\n"
            . "export const Channel = window.myphp.Channel;\n"
            . "const call = <T,>(method: string, ...args: unknown[]): Promise<T> => window.myphp.call<T>(method, ...args);\n"
            . "const on = (name: string, fn: (payload: unknown) => void) => window.myphp.on(name, fn);\n"
            . "export const isCallError = (e: unknown): boolean => window.myphp.isCallError(e);\n";
        foreach (self::$interfaces as $decl) {
            $out .= "\n$decl";
        }
        $out .= $services;
        if ($events !== '') {
            $out .= "\n/** Events PHP emits; each returns a function that stops listening. */\nexport const events = {\n$events} as const;\n";
        }
        return $out;
    }

    private static function type(?ReflectionType $t, ?string $doc): string
    {
        if ($doc !== null && $doc !== '') {
            return self::docType($doc);
        }
        if ($t === null) {
            return 'unknown';
        }
        if ($t instanceof ReflectionUnionType) {
            return implode(' | ', array_map(fn($x) => self::type($x, null), $t->getTypes()));
        }
        if (!$t instanceof ReflectionNamedType) {
            return 'unknown';
        }
        $ts = self::named($t->getName());
        return $t->allowsNull() && $ts !== 'null' && $ts !== 'void' && $ts !== 'unknown' ? "$ts | null" : $ts;
    }

    private static function named(string $php): string
    {
        return match ($php) {
            'int', 'float' => 'number',
            'string' => 'string',
            'bool', 'true', 'false' => 'boolean',
            'void' => 'void',
            'null' => 'null',
            'array', 'mixed', 'object' => 'unknown',
            Channel::class => 'Channel<unknown>',
            'self', 'static' => 'unknown',
            default => self::interface($php),
        };
    }

    /** A PHPDoc type such as `Note[]`, `list<Note>`, `array<string, int>`, `?Note`, `Note|null`. */
    private static function docType(string $doc): string
    {
        $doc = trim($doc);
        if (str_starts_with($doc, '?')) {
            return self::docType(substr($doc, 1)) . ' | null';
        }
        if (str_contains($doc, '|')) {
            return implode(' | ', array_map(self::docType(...), explode('|', $doc)));
        }
        if (str_ends_with($doc, '[]')) {
            return self::docType(substr($doc, 0, -2)) . '[]';
        }
        if (preg_match('/^(\\\\?MyPHP\\\\)?Channel<\s*(.+)\s*>$/', $doc, $m)) {
            return 'Channel<' . self::docType($m[2]) . '>';
        }
        if (preg_match('/^(list|array|iterable)<\s*([^,>]+)\s*>$/', $doc, $m)) {
            return self::docType($m[2]) . '[]';
        }
        if (preg_match('/^array<\s*([^,]+)\s*,\s*(.+)>$/', $doc, $m)) {
            return 'Record<' . self::docType($m[1]) . ', ' . self::docType($m[2]) . '>';
        }
        return self::named(ltrim($doc, '\\'));
    }

    /** Declares the interface for a class (once) and returns its name. */
    private static function interface(string $class): string
    {
        if (!class_exists($class)) {
            return 'unknown';
        }
        $rc = new ReflectionClass($class);
        $name = $rc->getShortName();
        if (!isset(self::$interfaces[$name])) {
            self::$interfaces[$name] = ''; // claims the name while properties recurse
            $props = '';
            foreach ($rc->getProperties(\ReflectionProperty::IS_PUBLIC) as $p) {
                if ($p->isStatic()) {
                    continue;
                }
                $doc = null;
                if (preg_match('/@var\s+(\S+)/', (string)$p->getDocComment(), $m)) {
                    $doc = $m[1];
                }
                $props .= self::tsdoc($p->getDocComment(), '  ') . '  ' . $p->getName() . ': ' . self::type($p->getType(), $doc) . ";\n";
            }
            self::$interfaces[$name] = self::tsdoc($rc->getDocComment(), '') . "export interface $name {\n$props}\n";
        }
        return $name;
    }

    private static function docTag(ReflectionMethod $m, string $tag, ?string $param = null): ?string
    {
        $doc = (string)$m->getDocComment();
        $re = $param === null ? "/@$tag\\s+(\\S+)/" : "/@$tag\\s+(\\S+)\\s+\\$$param\\b/";
        return preg_match($re, $doc, $x) ? $x[1] : null;
    }

    /** The description lines of a docblock as TSDoc, or nothing. */
    private static function tsdoc(string|false $doc, string $indent): string
    {
        if ($doc === false || $doc === '') {
            return '';
        }
        $lines = [];
        foreach (preg_split('/\R/', trim($doc, "/* \t\n")) as $line) {
            $line = trim(ltrim(trim($line), '*'));
            if ($line === '' || str_starts_with($line, '@')) {
                if ($line !== '' || $lines === []) {
                    continue;
                }
            }
            $lines[] = $line;
        }
        if ($lines === []) {
            return '';
        }
        return count($lines) === 1
            ? "$indent/** {$lines[0]} */\n"
            : "$indent/**\n" . implode('', array_map(fn($l) => "$indent * $l\n", $lines)) . "$indent */\n";
    }
}
