<?php
declare(strict_types=1);

namespace MyPHP\Native\Build;

use RuntimeException;

/**
 * FFIgen for MyPHP (inspired by Flutter 3.50's package:ffigen):
 * Generates type-safe, zero-overhead PHP 8.5 wrapper classes for:
 *  1. C header files (.h): structs, enums, constants, and functions over FFI::cdef().
 *  2. Apple Objective-C classes & frameworks (macOS & iOS): maps selectors and
 *     Objective-C types to `MyPHP\Native\ObjC::msg('ret:args', ...)` calls with
 *     full PHP type hints, IDE autocomplete, and NSString automatic conversion.
 */
final class FfiGen
{
    /**
     * Generates a type-safe PHP wrapper class from a C header source string or file.
     *
     * @param string $headerContent Raw C header declarations
     * @param string $className     Generated PHP class name (e.g. 'SqliteBindings')
     * @param string $namespace     PHP namespace (e.g. 'App\Native')
     * @param ?string $library      Shared library path/name passed to FFI::cdef()
     */
    public static function fromCHeader(
        string $headerContent,
        string $className,
        string $namespace = 'App\\Native',
        ?string $library = null
    ): string {
        // Strip C comments, extern "C" guards, and preprocessor directives for parsing
        $clean = (string)preg_replace('~/\*.*?\*/~s', '', $headerContent);
        $clean = (string)preg_replace('~//[^\r\n]*~', '', $clean);
        $clean = (string)preg_replace('/^[ \t]*#ifdef\s+__cplusplus\s+extern\s+"C"\s*\{\s*#endif/m', '', $clean);
        $clean = (string)preg_replace('/^[ \t]*#ifdef\s+__cplusplus\s+\}\s*#endif/m', '', $clean);
        $clean = (string)preg_replace('/\bextern\s+"C"\s+/', '', $clean);

        // Extract #define integer/float/string constants before stripping directives
        $constants = [];
        if (preg_match_all('/^[ \t]*#define\s+([A-Z_][A-Z0-9_]*)\s+(-?(?:0x[0-9a-fA-F]+|\d+(?:\.\d+)?))\b/m', $clean, $dm, PREG_SET_ORDER)) {
            foreach ($dm as $m) {
                $constants[$m[1]] = $m[2];
            }
        }

        $cdefLines = [];
        foreach (explode("\n", $clean) as $line) {
            $trimmed = trim($line);
            if ($trimmed === '' || str_starts_with($trimmed, '#')) {
                continue;
            }
            $cdefLines[] = self::normalizeWin32Annotations($line);
        }
        $cdefSource = trim(implode("\n", $cdefLines));

        // Prepend standard Win32 typedefs if the header uses Win32 types (HANDLE, HWND, DWORD, BOOL, LPCWSTR, etc.)
        $win32Typedefs = self::win32PreambleFor($cdefSource);
        $fullCdefSource = $win32Typedefs !== '' ? ($win32Typedefs . "\n" . $cdefSource) : $cdefSource;

        // Extract enum constants: enum Foo { A = 1, B = 2 };
        if (preg_match_all('/enum\s+\w*\s*\{([^}]+)\}/s', $cdefSource, $em)) {
            foreach ($em[1] as $body) {
                $val = 0;
                foreach (explode(',', $body) as $item) {
                    $item = trim($item);
                    if ($item === '') { continue; }
                    if (preg_match('/^([A-Za-z_]\w*)\s*=\s*(-?(?:0x[0-9a-fA-F]+|\d+))$/', $item, $im)) {
                        $val = str_starts_with($im[2], '0x') ? hexdec($im[2]) : (int)$im[2];
                        $constants[$im[1]] = (string)$val;
                        $val++;
                    } elseif (preg_match('/^([A-Za-z_]\w*)$/', $item, $im)) {
                        $constants[$im[1]] = (string)$val++;
                    }
                }
            }
        }

        // Extract top-level C function declarations
        $functions = self::parseCFunctions($cdefSource);

        $libExpr = $library !== null ? var_export($library, true) : 'null';
        $cdefExport = var_export($fullCdefSource, true);

        $out = [];
        $out[] = '<?php';
        $out[] = '// AUTO-GENERATED BY `myphp ffigen` — DO NOT EDIT BY HAND.';
        $out[] = 'declare(strict_types=1);';
        $out[] = '';
        if ($namespace !== '') {
            $out[] = "namespace $namespace;";
            $out[] = '';
        }
        $out[] = 'use FFI;';
        $out[] = 'use FFI\CData;';
        $out[] = '';
        $out[] = "final class $className";
        $out[] = '{';

        foreach ($constants as $k => $v) {
            $out[] = "    public const $k = $v;";
        }
        if ($constants !== []) {
            $out[] = '';
        }

        $out[] = "    public const LIBRARY = $libExpr;";
        $out[] = '';
        $out[] = "    public const CDEF = $cdefExport;";
        $out[] = '';
        $out[] = '    private static ?FFI $ffi = null;';
        $out[] = '';
        $out[] = '    /**';
        $out[] = '     * Resolves a cross-platform library stem or file name (e.g. "quant_sweep")';
        $out[] = '     * to the running platform\'s shared library (.dylib / .so / .dll) inside the';
        $out[] = '     * app bundle resources, project resources/<os>-<arch>/, or system search path.';
        $out[] = '     */';
        $out[] = '    public static function resolveLibrary(?string $library = null): ?string';
        $out[] = '    {';
        $out[] = '        $raw = $library ?? self::LIBRARY;';
        $out[] = '        if ($raw === null || $raw === \'\') {';
        $out[] = '            return null;';
        $out[] = '        }';
        $out[] = '        if (is_file($raw) || str_contains($raw, \'/\') || str_contains($raw, \'\\\\\')) {';
        $out[] = '            return $raw;';
        $out[] = '        }';
        $out[] = '        $os = match (PHP_OS_FAMILY) { \'Darwin\' => \'darwin\', \'Windows\' => \'windows\', default => strtolower(PHP_OS_FAMILY) };';
        $out[] = '        $arch = match (strtolower(php_uname(\'m\'))) { \'x86_64\', \'amd64\' => \'amd64\', \'arm64\', \'aarch64\' => \'arm64\', default => strtolower(php_uname(\'m\')) };';
        $out[] = '        $candidates = [];';
        $out[] = '        if (str_contains($raw, \'.so.\')) {';
        $out[] = '            $candidates[] = $raw;';
        $out[] = '        } else {';
        $out[] = '            $stem = (string)preg_replace(\'/\.(?:dylib|dll|so)$/i\', \'\', $raw);';
        $out[] = '            $bare = str_starts_with($stem, \'lib\') && strlen($stem) > 3 ? substr($stem, 3) : $stem;';
        $out[] = '            $native = match ($os) {';
        $out[] = '                \'darwin\' => ["lib{$bare}.dylib", "{$bare}.dylib"],';
        $out[] = '                \'windows\' => ["{$bare}.dll", "lib{$bare}.dll"],';
        $out[] = '                default => ["lib{$bare}.so", "{$bare}.so"],';
        $out[] = '            };';
        $out[] = '            foreach ([...$native, $raw] as $c) {';
        $out[] = '                if (!in_array($c, $candidates, true)) {';
        $out[] = '                    $candidates[] = $c;';
        $out[] = '                }';
        $out[] = '            }';
        $out[] = '        }';
        $out[] = '        $dirs = [];';
        $out[] = '        if (class_exists(\\MyPHP\\Native\\Bundle::class)) {';
        $out[] = '            $res = \\MyPHP\\Native\\Bundle::resources();';
        $out[] = '            if ($res !== null) { $dirs[] = $res; }';
        $out[] = '            $exe = \\MyPHP\\Native\\Bundle::executable();';
        $out[] = '            if ($exe !== \'\') { $dirs[] = dirname($exe); }';
        $out[] = '        }';
        $out[] = '        $roots = [__DIR__, dirname(__DIR__), dirname(__DIR__, 2), dirname(__DIR__, 3)];';
        $out[] = '        $cwd = getcwd();';
        $out[] = '        if (is_string($cwd) && $cwd !== \'\') { $roots[] = $cwd; }';
        $out[] = '        foreach ($roots as $r) {';
        $out[] = '            $dirs[] = "$r/resources/$os-$arch";';
        $out[] = '            $dirs[] = "$r/resources/$os";';
        $out[] = '            $dirs[] = "$r/resources";';
        $out[] = '        }';
        $out[] = '        foreach ($dirs as $dir) {';
        $out[] = '            foreach ($candidates as $cand) {';
        $out[] = '                $p = "$dir/$cand";';
        $out[] = '                if (is_file($p)) {';
        $out[] = '                    return $p;';
        $out[] = '                }';
        $out[] = '            }';
        $out[] = '        }';
        $out[] = '        return $candidates[0];';
        $out[] = '    }';
        $out[] = '';
        $out[] = '    public static function available(?string $library = null): bool';
        $out[] = '    {';
        $out[] = '        if (!extension_loaded(\'ffi\')) {';
        $out[] = '            return false;';
        $out[] = '        }';
        $out[] = '        try {';
        $out[] = '            self::ffi($library);';
        $out[] = '            return true;';
        $out[] = '        } catch (\\Throwable) {';
        $out[] = '            return false;';
        $out[] = '        }';
        $out[] = '    }';
        $out[] = '';
        $out[] = '    public static function ffi(?string $library = null): FFI';
        $out[] = '    {';
        $out[] = '        if ($library !== null) {';
        $out[] = '            return FFI::cdef(self::CDEF, self::resolveLibrary($library));';
        $out[] = '        }';
        $out[] = '        return self::$ffi ??= FFI::cdef(self::CDEF, self::resolveLibrary());';
        $out[] = '    }';
        $out[] = '';
        $out[] = '    public static function new(string $type, bool $owned = true, bool $persistent = false): CData';
        $out[] = '    {';
        $out[] = '        return self::ffi()->new($type, $owned, $persistent);';
        $out[] = '    }';

        foreach ($functions as $fn) {
            $out[] = '';
            $paramDocs = [];
            $paramSig = [];
            $callArgs = [];
            foreach ($fn['params'] as $idx => [$pType, $pName]) {
                [$phpType, $docType] = self::cTypeToPhp($pType, false);
                $safeName = $pName !== '' ? $pName : "arg$idx";
                $paramSig[] = ($phpType !== '' ? "$phpType " : '') . "\$$safeName";
                $callArgs[] = "\$$safeName";
                if ($docType !== '') {
                    $paramDocs[] = "     * @param $docType \$$safeName";
                }
            }
            [$retPhp, $retDoc] = self::cTypeToPhp($fn['return'], true);
            if ($paramDocs !== [] || $retDoc !== '') {
                $out[] = '    /**';
                foreach ($paramDocs as $pd) { $out[] = $pd; }
                if ($retDoc !== '') { $out[] = "     * @return $retDoc"; }
                $out[] = '     */';
            }
            $retDecl = $retPhp !== '' ? ": $retPhp" : '';
            $name = $fn['name'];
            $sigStr = implode(', ', $paramSig);
            $callStr = implode(', ', $callArgs);
            $out[] = "    public static function $name($sigStr)$retDecl";
            $out[] = '    {';
            if ($retPhp === 'void') {
                $out[] = "        self::ffi()->$name($callStr);";
            } else {
                $out[] = "        return self::ffi()->$name($callStr);";
            }
            $out[] = '    }';
        }

        $out[] = '}';
        $out[] = '';

        return implode("\n", $out);
    }

    /**
     * Generates a type-safe PHP wrapper class for an Apple Objective-C class
     * (macOS / iOS) from an `@interface` declaration or SDK header.
     *
     * Automatically maps Objective-C types (`id`, `NSString*`, `BOOL`, `NSInteger`,
     * `NSUInteger`, `CGFloat`, `NSRect`, `CGPoint`, `CGSize`) to `ObjC::msg('ret:args', ...)`
     * signatures and camelCases multi-part selectors (`initWithFrame:device:` -> `initWithFrameDevice`).
     */
    public static function fromObjCHeader(
        string $objcSource,
        string $targetClass,
        string $namespace = 'App\\Native\\Apple',
        array $frameworks = ['Foundation']
    ): string {
        $methods = self::parseObjCMethods($objcSource, $targetClass);
        $fwExport = '[' . implode(', ', array_map(fn(string $f) => var_export($f, true), $frameworks)) . ']';

        $out = [];
        $out[] = '<?php';
        $out[] = '// AUTO-GENERATED BY `myphp ffigen --objc` — DO NOT EDIT BY HAND.';
        $out[] = 'declare(strict_types=1);';
        $out[] = '';
        if ($namespace !== '') {
            $out[] = "namespace $namespace;";
            $out[] = '';
        }
        $out[] = 'use FFI\CData;';
        $out[] = 'use MyPHP\Native\ObjC;';
        $out[] = '';
        $out[] = "/**";
        $out[] = " * Type-safe Objective-C wrapper for `$targetClass` over `MyPHP\\Native\\ObjC`.";
        $out[] = " */";
        $out[] = "final class $targetClass";
        $out[] = '{';
        $out[] = '    public function __construct(public readonly mixed $handle) {}';
        $out[] = '';
        $out[] = '    public static function cls(): mixed';
        $out[] = '    {';
        $out[] = "        ObjC::boot($fwExport);";
        $out[] = "        return ObjC::cls('$targetClass');";
        $out[] = '    }';
        $out[] = '';
        $out[] = '    public static function alloc(): self';
        $out[] = '    {';
        $out[] = "        ObjC::boot($fwExport);";
        $out[] = "        return new self(ObjC::alloc('$targetClass'));";
        $out[] = '    }';

        $usedNames = ['cls' => true, 'alloc' => true, '__construct' => true];

        foreach ($methods as $m) {
            $phpMethod = $m['phpName'];
            if (isset($usedNames[$phpMethod])) {
                continue;
            }
            $usedNames[$phpMethod] = true;

            $retLetter = self::objcTypeToLetter($m['return']);
            $argLetters = '';
            $paramDecls = [];
            $callArgs = [];

            foreach ($m['params'] as $idx => [$pType, $pName]) {
                $letter = self::objcTypeToLetter($pType);
                $argLetters .= $letter;
                $phpParamType = self::objcTypeToPhp($pType, false, $targetClass);
                $safeName = $pName !== '' ? $pName : "arg$idx";
                $paramDecls[] = ($phpParamType !== '' ? "$phpParamType " : '') . "\$$safeName";

                if (self::isNSString($pType)) {
                    $callArgs[] = "is_string(\$$safeName) ? ObjC::str(\$$safeName) : \$$safeName";
                } elseif ($letter === 'p') {
                    $callArgs[] = "\$$safeName instanceof self ? \$$safeName" . '->handle : (is_object($' . $safeName . ') && !$' . $safeName . ' instanceof CData && property_exists($' . $safeName . ", 'handle') ? \$$safeName" . "->handle : \$$safeName)";
                } else {
                    $callArgs[] = "\$$safeName";
                }
            }

            $sig = "$retLetter:$argLetters";
            $selector = $m['selector'];
            $isStatic = $m['isStatic'];
            $retPhp = self::objcTypeToPhp($m['return'], true, $targetClass);
            $retDecl = $retPhp !== '' ? ": $retPhp" : '';
            $staticKw = $isStatic ? 'static ' : '';
            $targetExpr = $isStatic ? 'self::cls()' : '$this->handle';
            $argsTail = $callArgs !== [] ? ', ' . implode(', ', $callArgs) : '';

            $out[] = '';
            $out[] = "    /** Selector: `$selector` (ObjC signature: `$sig`) */";
            $out[] = "    public {$staticKw}function $phpMethod(" . implode(', ', $paramDecls) . ")$retDecl";
            $out[] = '    {';
            if ($isStatic) {
                $out[] = "        ObjC::boot($fwExport);";
            }
            $msgCall = "ObjC::msg('$sig', $targetExpr, '$selector'$argsTail)";
            if ($retLetter === 'v') {
                $out[] = "        $msgCall;";
            } elseif (self::isNSString($m['return'])) {
                $out[] = "        return ObjC::phpStr($msgCall);";
            } elseif ($retPhp === 'self') {
                $out[] = "        \$res = $msgCall;";
                $out[] = "        return new self(\$res);";
            } else {
                $out[] = "        return $msgCall;";
            }
            $out[] = '    }';
        }

        $out[] = '}';
        $out[] = '';

        return implode("\n", $out);
    }

    /**
     * @return list<array{name: string, return: string, params: list<array{0: string, 1: string}>}>
     */
    public static function parseCFunctions(string $cdefSource): array
    {
        // Remove struct/union/enum blocks so we only match top-level function prototypes
        $stripped = (string)preg_replace('/\b(?:struct|union|enum)\s+\w*\s*\{[^}]*\}/s', 'struct_t', $cdefSource);
        $lines = explode(';', $stripped);
        $functions = [];

        foreach ($lines as $stmt) {
            $stmt = trim((string)preg_replace('/\s+/', ' ', $stmt));
            if ($stmt === '' || str_starts_with($stmt, 'typedef ') || str_starts_with($stmt, 'extern void*')) {
                continue;
            }
            $stmt = (string)preg_replace('/^extern\s+/', '', $stmt);
            if (!preg_match('/^([A-Za-z_][\w\s\*]+?)\s*\*\s*([A-Za-z_]\w*)\s*\(([^)]*)\)$|^([A-Za-z_][\w\s\*]*?)\s+([A-Za-z_]\w*)\s*\(([^)]*)\)$/', $stmt, $m)) {
                continue;
            }
            if ($m[1] !== '') {
                $retType = trim($m[1]) . '*';
                $fnName  = $m[2];
                $rawArgs = trim($m[3]);
            } else {
                $retType = trim($m[4]);
                $fnName  = $m[5];
                $rawArgs = trim($m[6]);
            }

            $params = [];
            if ($rawArgs !== '' && $rawArgs !== 'void') {
                foreach (explode(',', $rawArgs) as $idx => $part) {
                    $part = trim($part);
                    if ($part === '' || $part === '...') { continue; }
                    if (preg_match('/^(.*?)(\*+)\s*([A-Za-z_]\w*)?$/', $part, $pm)) {
                        $params[] = [trim($pm[1]) . $pm[2], $pm[3] ?? "arg$idx"];
                    } elseif (preg_match('/^(.*)\s+([A-Za-z_]\w*)$/', $part, $pm)) {
                        $params[] = [trim($pm[1]), $pm[2]];
                    } else {
                        $params[] = [$part, "arg$idx"];
                    }
                }
            }

            $functions[] = [
                'name'   => $fnName,
                'return' => $retType,
                'params' => $params,
            ];
        }

        return $functions;
    }

    /**
     * Parses Objective-C `@interface` method declarations (`+` class methods, `-` instance methods)
     * and `@property` declarations.
     *
     * @return list<array{isStatic: bool, return: string, selector: string, phpName: string, params: list<array{0: string, 1: string}>}>
     */
    public static function parseObjCMethods(string $objcSource, string $targetClass): array
    {
        $clean = (string)preg_replace('~/\*.*?\*/~s', '', $objcSource);
        $clean = (string)preg_replace('~//[^\r\n]*~', '', $clean);

        // Isolate @interface $targetClass ... @end if present
        if (preg_match('/@interface\s+' . preg_quote($targetClass, '/') . '\b(.*?)@end/s', $clean, $im)) {
            $body = $im[1];
        } else {
            $body = $clean;
        }

        $methods = [];

        // 1. Parse @property declarations -> getter + setter (unless readonly)
        if (preg_match_all('/@property\s*(?:\(([^)]*)\))?\s*([^;]+);/', $body, $pm, PREG_SET_ORDER)) {
            foreach ($pm as $p) {
                $attrs = $p[1] ?? '';
                $attrsLower = strtolower($attrs);
                $decl  = trim($p[2]);
                // Strip trailing API_AVAILABLE(...) / NS_AVAILABLE(...) / UIKIT_AVAILABLE(...) macros
                $decl  = trim((string)preg_replace('/\b(?:NS_|API_|UIKIT_|__)\w+(?:\s*\([^)]*\))?.*$/', '', $decl));
                if (preg_match('/^(.*?)(\*?\s*)([A-Za-z_]\w*)$/', $decl, $dm)) {
                    $propType = trim($dm[1] . $dm[2]);
                    $propName = $dm[3];
                    $getterSel = $propName;
                    if (preg_match('/\bgetter\s*=\s*([A-Za-z_]\w*)/', $attrs, $gm)) {
                        $getterSel = $gm[1];
                    }
                    $methods[] = [
                        'isStatic' => str_contains($attrsLower, 'class'),
                        'return'   => $propType,
                        'selector' => $getterSel,
                        'phpName'  => $propName,
                        'params'   => [],
                    ];
                    if (!str_contains($attrsLower, 'readonly')) {
                        $setter = 'set' . ucfirst($propName) . ':';
                        $methods[] = [
                            'isStatic' => str_contains($attrsLower, 'class'),
                            'return'   => 'void',
                            'selector' => $setter,
                            'phpName'  => 'set' . ucfirst($propName),
                            'params'   => [[$propType, 'value']],
                        ];
                    }
                }
            }
        }

        // 2. Parse `+ (ret)sel...;` and `- (ret)sel...;` methods
        if (preg_match_all('/([+-])\s*\(([^)]+)\)\s*([^;]+);/s', $body, $mm, PREG_SET_ORDER)) {
            foreach ($mm as $m) {
                $isStatic = $m[1] === '+';
                $retType  = trim($m[2]);
                $rest     = trim((string)preg_replace('/\s+/', ' ', $m[3]));
                // Strip NS_AVAILABLE / API_AVAILABLE / NS_SWIFT_NAME macros at end
                $rest     = trim((string)preg_replace('/\b(?:NS_|API_|__)\w+\s*(?:\([^)]*\))?.*$/', '', $rest));

                if (!str_contains($rest, ':')) {
                    // Zero-arg selector
                    $sel = preg_replace('/[^A-Za-z0-9_]/', '', $rest);
                    if ($sel === '') { continue; }
                    $methods[] = [
                        'isStatic' => $isStatic,
                        'return'   => $retType,
                        'selector' => $sel,
                        'phpName'  => $sel,
                        'params'   => [],
                    ];
                    continue;
                }

                // Multi-part selector: `part1:(Type1)arg1 part2:(Type2)arg2`
                if (preg_match_all('/([A-Za-z_]\w*)\s*:\s*\(([^)]+)\)\s*([A-Za-z_]\w*)/', $rest, $parts, PREG_SET_ORDER)) {
                    $selParts = [];
                    $phpParts = [];
                    $params   = [];
                    foreach ($parts as $idx => $pt) {
                        $selParts[] = $pt[1] . ':';
                        $phpParts[] = $idx === 0 ? $pt[1] : ucfirst($pt[1]);
                        $params[]   = [trim($pt[2]), $pt[3]];
                    }
                    $methods[] = [
                        'isStatic' => $isStatic,
                        'return'   => $retType,
                        'selector' => implode('', $selParts),
                        'phpName'  => implode('', $phpParts),
                        'params'   => $params,
                    ];
                }
            }
        }

        return $methods;
    }

    /**
     * Maps a C type to [phpTypeHint, phpDocType].
     *
     * @return array{0: string, 1: string}
     */
    private static function cTypeToPhp(string $cType, bool $isReturn): array
    {
        $t = trim((string)preg_replace('/\bconst\b/', '', $cType));
        if ($t === 'void') {
            return [$isReturn ? 'void' : '', ''];
        }
        if ($t === 'char*' || $t === 'char *') {
            return [$isReturn ? 'string|CData|null' : 'string|CData|null', 'string|CData|null'];
        }
        if (str_contains($t, '*')) {
            return ['mixed', 'CData|null'];
        }
        if (in_array($t, ['bool', '_Bool', 'BOOL', 'BOOLEAN', 'gboolean'], true)) {
            return ['bool|int', ''];
        }
        if (in_array($t, ['float', 'double', 'FLOAT', 'gfloat', 'gdouble'], true)) {
            return ['float', ''];
        }
        if (preg_match('/^(?:u?int\d+_t|unsigned|signed|int|long|short|size_t|ssize_t|char|DWORD|WORD|BYTE|LONG|ULONG|UINT|INT|WPARAM|LPARAM|LRESULT|HRESULT|ATOM|gint|guint|glong|gulong|gshort|gushort|gint8|guint8|gint16|guint16|gint32|guint32|gint64|guint64|gsize|gssize|GType|GQuark)\b/', $t)) {
            return ['int', ''];
        }
        if (preg_match('/^(?:HANDLE|HWND|HINSTANCE|HMODULE|HDC|HICON|HCURSOR|HBRUSH|HFONT|HMENU|LPVOID|LPCVOID|LPSTR|LPCSTR|LPWSTR|LPCWSTR|PVOID|gpointer|gconstpointer|GtkWidget|GdkWindow|GObject|GError)\b/', $t)) {
            return ['mixed', 'CData|string|null'];
        }
        return ['mixed', ''];
    }

    /**
     * Strips Windows SAL annotations (`_In_`, `_Out_opt_`, `IN`, `OUT`), calling conventions
     * (`WINAPI`, `APIENTRY`, `CALLBACK`, `__stdcall`, `__cdecl`), `__declspec(dllexport|dllimport)`,
     * and Linux / GCC / GLib / GTK visibility & attribute macros (`GDK_AVAILABLE_IN_ALL`,
     * `GLIB_AVAILABLE_IN_ALL`, `G_GNUC_*`, `__attribute__((...))`, `__THROW`, `__nonnull`)
     * so PHP `FFI::cdef()` can parse Windows and Linux system headers directly.
     */
    public static function normalizeWin32Annotations(string $line): string
    {
        // Windows macros
        $line = (string)preg_replace('/__declspec\s*\(\s*(?:dllexport|dllimport)\s*\)/i', '', $line);
        $line = (string)preg_replace('/\b(?:WINAPI|APIENTRY|CALLBACK|WINBASEAPI|WINUSERAPI|__stdcall|__cdecl|__fastcall)\b/', '', $line);
        $line = (string)preg_replace('/\b_(?:In|Out|Inout|Reserved)(?:_opt|_z|_reads|_writes|_bytes|_count|[A-Za-z0-9_])*\s*(?:\([^)]*\))?/', '', $line);
        $line = (string)preg_replace('/\b(?:IN|OUT|OPTIONAL)\b(?=\s+[A-Za-z_])/', '', $line);

        // Linux / GCC / glibc / GLib / GTK macros
        $line = (string)preg_replace('/__attribute__\s*\(\s*\([^)]*\)\s*\)/', '', $line);
        $line = (string)preg_replace('/\b(?:G_GNUC_[A-Z0-9_]+|__nonnull|__wur)\s*(?:\([^)]*\))?/', '', $line);
        $line = (string)preg_replace('/\b(?:GDK|GTK|GLIB|GIO|PANGO|CAIRO)_(?:AVAILABLE|DEPRECATED)[A-Z0-9_]*\b/', '', $line);
        $line = (string)preg_replace('/\b(?:G_BEGIN_DECLS|G_END_DECLS|__THROW|__NTH|__restrict|__extension__)\b/', '', $line);

        return (string)preg_replace('/[ \t]{2,}/', ' ', $line);
    }

