<?php
declare(strict_types=1);

namespace MyPHP\Native\Build;

use MyPHP\Native\Jni;
use RuntimeException;

/**
 * JNIgen for MyPHP (inspired by Flutter 3.50's package:jnigen):
 * Inspects Java/Kotlin classes via `javap -s -public` (from Android SDK `android.jar`
 * or custom `.jar` / `.class` files) and generates type-safe PHP 8.5 wrapper classes
 * that call `MyPHP\Native\Jni` directly and synchronously.
 */
final class JniGen
{
    /**
     * Locates the default `android.jar` from ANDROID_HOME / ~/Library/Android/sdk.
     */
    public static function defaultAndroidJar(): string
    {
        $sdk = Emulators::androidSdk();
        if ($sdk === '') {
            return '';
        }
        $jars = glob("$sdk/platforms/*/android.jar") ?: [];
        natsort($jars);
        return $jars !== [] ? end($jars) : '';
    }

    /**
     * Inspects $javaClass (e.g. `android.os.BatteryManager` or `java.util.UUID`) using `javap -s -public`
     * and returns the generated PHP wrapper class source.
     */
    public static function fromJavaClass(
        string $javaClass,
        string $namespace = 'App\\Native\\Android',
        ?string $classpath = null
    ): string {
        $javap = Cmd::look('javap') ?: '/opt/homebrew/opt/openjdk@17/bin/javap';
        if (!is_executable($javap)) {
            throw new RuntimeException('jnigen requires `javap` (install OpenJDK 17+)');
        }

        $cp = $classpath ?: self::defaultAndroidJar();
        $cmd = [$javap, '-s', '-public'];
        if ($cp !== '') {
            array_push($cmd, '-cp', $cp);
        }
        $cmd[] = $javaClass;

        [$code, $out] = Cmd::output($cmd);
        if ($code !== 0) {
            throw new RuntimeException("javap failed for $javaClass: " . trim($out));
        }

        return self::fromJavapOutput($out, $javaClass, $namespace);
    }

    /**
     * Parses `javap -s -public` output into a type-safe PHP 8.5 wrapper class over `MyPHP\Native\Jni`.
     */
    public static function fromJavapOutput(
        string $javapOutput,
        string $javaClass,
        string $namespace = 'App\\Native\\Android'
    ): string {
        $slashClass = str_replace('.', '/', $javaClass);
        $shortName  = substr(strrchr('.' . str_replace('$', '_', $javaClass), '.'), 1);

        $lines = explode("\n", str_replace("\r\n", "\n", $javapOutput));
        $methods = [];
        $n = count($lines);

        for ($i = 0; $i < $n; $i++) {
            $line = trim($lines[$i]);
            if (!str_starts_with($line, 'public ') || !str_ends_with($line, ';')) {
                continue;
            }
            // Look ahead for `descriptor: (...)...`
            $descLine = isset($lines[$i + 1]) ? trim($lines[$i + 1]) : '';
            if (!preg_match('/^descriptor:\s*(\S+)$/', $descLine, $dm)) {
                continue;
            }
            $descriptor = $dm[1];
            $i++; // consume descriptor line

            // Only process method/constructor descriptors starting with '('
            if (!str_starts_with($descriptor, '(')) {
                continue;
            }

            $isStatic = str_contains($line, ' static ');
            if (preg_match('/(?:^|\s)([A-Za-z0-9_$.]+)\s*\(/', $line, $mm)) {
                $mName = $mm[1];
            } else {
                continue;
            }

            $isCtor = ($mName === $javaClass || str_ends_with($javaClass, '.' . $mName) || str_ends_with($javaClass, '$' . $mName));
            $methods[] = [
                'name'       => $isCtor ? '<init>' : $mName,
                'isCtor'     => $isCtor,
                'isStatic'   => $isStatic,
                'descriptor' => $descriptor,
            ];
        }

        $out = [];
        $out[] = '<?php';
        $out[] = '// AUTO-GENERATED BY `myphp jnigen` — DO NOT EDIT BY HAND.';
        $out[] = 'declare(strict_types=1);';
        $out[] = '';
        if ($namespace !== '') {
            $out[] = "namespace $namespace;";
            $out[] = '';
        }
        $out[] = 'use MyPHP\Native\Jni;';
        $out[] = '';
        $out[] = "/**";
        $out[] = " * Type-safe JNI wrapper for `$javaClass` over `MyPHP\\Native\\Jni`.";
        $out[] = " */";
        $out[] = "final class $shortName";
        $out[] = '{';
        $out[] = "    public const JAVA_CLASS = '$slashClass';";
        $out[] = '';
        $out[] = '    public function __construct(public readonly mixed $handle) {}';
        $out[] = '';
        $out[] = '    public function release(): void';
        $out[] = '    {';
        $out[] = '        Jni::release($this->handle);';
        $out[] = '    }';

        $nameCounts = [];
        foreach ($methods as $m) {
            $base = $m['isCtor'] ? 'create' : $m['name'];
            $nameCounts[$base] = ($nameCounts[$base] ?? 0) + 1;
        }

        $usedNames = ['__construct' => true, 'release' => true];
        $overloadIdx = [];

        foreach ($methods as $m) {
            $desc = $m['descriptor'];
            $argDescs = Jni::parseArgDescriptors($desc);
            $retDesc  = substr($desc, (int)strrpos($desc, ')') + 1);

            $baseName = $m['isCtor'] ? 'create' : $m['name'];
            if (($nameCounts[$baseName] ?? 0) > 1) {
                $idx = ($overloadIdx[$baseName] ?? 0) + 1;
                $overloadIdx[$baseName] = $idx;
                $phpName = $idx === 1 ? $baseName : "{$baseName}_{$idx}";
            } else {
                $phpName = $baseName;
            }
            if (isset($usedNames[$phpName])) {
                continue;
            }
            $usedNames[$phpName] = true;

            $paramDecls = [];
            $callArgs = [];
            foreach ($argDescs as $aIdx => $ad) {
                $pType = self::jniDescToPhpType($ad, false, $slashClass);
                $paramDecls[] = ($pType !== '' ? "$pType " : '') . "\$arg$aIdx";
                $callArgs[] = "\$arg$aIdx";
            }

            $argsTail = $callArgs !== [] ? ', ' . implode(', ', $callArgs) : '';

            if ($m['isCtor']) {
                $out[] = '';
                $out[] = "    /** JNI constructor: `$desc` */";
                $out[] = "    public static function $phpName(" . implode(', ', $paramDecls) . "): self";
                $out[] = '    {';
                $out[] = "        return new self(Jni::newObject(self::JAVA_CLASS, '$desc'$argsTail));";
                $out[] = '    }';
                continue;
            }

            $retPhp = self::jniDescToPhpType($retDesc, true, $slashClass);
            $retDecl = $retPhp !== '' ? ": $retPhp" : '';
            $staticKw = $m['isStatic'] ? 'static ' : '';
            $jName = $m['name'];

            $out[] = '';
            $out[] = "    /** JNI method: `$jName` (`$desc`) */";
            $out[] = "    public {$staticKw}function $phpName(" . implode(', ', $paramDecls) . ")$retDecl";
            $out[] = '    {';
            $callExpr = $m['isStatic']
                ? "Jni::callStatic(self::JAVA_CLASS, '$jName', '$desc'$argsTail)"
                : "Jni::call(\$this->handle, self::JAVA_CLASS, '$jName', '$desc'$argsTail)";

            if ($retPhp === 'void') {
                $out[] = "        $callExpr;";
            } elseif ($retPhp === '?self') {
                $out[] = "        \$res = $callExpr;";
                $out[] = "        return \$res !== null ? new self(\$res) : null;";
            } else {
                $out[] = "        return $callExpr;";
            }
            $out[] = '    }';
        }

        $out[] = '}';
        $out[] = '';

        return implode("\n", $out);
    }

    private static function jniDescToPhpType(string $desc, bool $isReturn, string $selfSlashClass): string
    {
        if ($desc === "L{$selfSlashClass};") {
            return $isReturn ? '?self' : 'mixed';
        }
        if ($desc === 'Ljava/lang/String;') {
            return $isReturn ? '?string' : 'string';
        }
        return match ($desc[0] ?? 'V') {
            'V' => $isReturn ? 'void' : '',
            'Z' => 'bool',
            'B', 'C', 'S', 'I', 'J' => 'int',
            'F', 'D' => 'float',
            default => 'mixed',
        };
    }
}
