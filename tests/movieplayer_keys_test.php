<?php
// The player's key bindings (UI\MoviePlayerKeys), as IINA's: input.conf read
// (IINA's own commands after "#@iina", comments), mpv's keys in their one
// form, a key pressed named as mpv names it, a binding shown as a Mac
// writes keys and its command read in words, written back.
declare(strict_types=1);

namespace MyPHP\Tests;

use MyPHP\Media\PlayerSettings;
use MyPHP\UI\{Context, Key, MoviePlayerKeys};

$m = MoviePlayerKeys::parse("# a comment\n\nSPACE cycle pause\n#@iina Ctrl+Meta+p toggle-pip\nMeta+L cycle-values loop \"inf\" \"no\"   # loops\nbroken\n");
same([['SPACE', ['cycle', 'pause'], false, null], ['Ctrl+Meta+p', ['toggle-pip'], true, null], ['Meta+L', ['cycle-values', 'loop', '"inf"', '"no"'], false, ' loops']],
    array_map(fn(array $x) => [$x['key'], $x['action'], $x['iina'], $x['comment']], $m), 'input.conf read: its keys, actions, IINA\'s own, comments');
same(['Alt+Meta+X', 'Meta+K', 'ESC', '_', 'PLUS', 'Ctrl+X', 'Shift+UP', '(', 'SHARP'],
    array_map([MoviePlayerKeys::class, 'normalize'], ['Meta+Alt+X', 'meta+shift+k', 'esc', 'Shift+-', 'Shift+=', 'CTRL+SHIFT+SHIFT+x', 'shift+up', 'Shift+(', '#']), 'mpv\'s keys in their one form');
same(['SPACE', 'Meta+l', 'Meta+L', 'Alt+x', 'Shift+UP', '(', 'ESC', 'Ctrl+Meta+f'],
    [MoviePlayerKeys::fromEvent(Key::SPACE, 0, ' '), MoviePlayerKeys::fromEvent(Key::L, Key::COMMAND, 'l'), MoviePlayerKeys::fromEvent(Key::L, Key::COMMAND | Key::SHIFT, 'L'),
     MoviePlayerKeys::fromEvent(Key::X, Key::OPTION, 'x'), MoviePlayerKeys::fromEvent(Key::UP, Key::SHIFT, "\u{F700}"), MoviePlayerKeys::fromEvent(Key::N9, Key::SHIFT, '('),
     MoviePlayerKeys::fromEvent(Key::ESCAPE, 0, "\e"), MoviePlayerKeys::fromEvent(Key::F, Key::CONTROL | Key::COMMAND, 'f')], 'a key pressed, named as mpv names it');
same(['␣', '⌃⌘P', '⇧⌘L', '⌥←', 'F1'], array_map(fn(string $k) => MoviePlayerKeys::displayKey(MoviePlayerKeys::mapping($k, 'x'), false), ['SPACE', 'Ctrl+Meta+p', 'Meta+L', 'Alt+LEFT', 'F1']), 'keys as a Mac writes them');
$c = null;
(new Headless(function (Context $ctx) use (&$c) { $c = $ctx; $ctx->column(); $ctx->end(); }, 400, 300))->frame();
same(['Seek forward 5s ', 'Seek backward 5s ', 'Set Pause to Yes', 'Volume +5', 'Multiply Speed by 2.0x', 'Cycle Subtitle track', 'Toggle Picture-in-Picture', 'Next media', 'Seek to next subtitle'],
    array_map(fn(string $a) => MoviePlayerKeys::displayAction($c, MoviePlayerKeys::mapping('x', $a), false), ['seek 5', 'seek -5', 'set pause yes', 'add volume 5', 'multiply speed 2.0', 'cycle sub', '@iina toggle-pip', 'playlist-next', 'sub-seek 1']),
    'commands read in words, as IINA reads them');
same('@iina toggle-pip', MoviePlayerKeys::displayAction($c, MoviePlayerKeys::mapping('x', '@iina toggle-pip'), true), 'or raw');
same("# Generated by IINA\n\nSPACE cycle pause\n#@iina Ctrl+Meta+p toggle-pip\nMeta+L cycle-values loop \"inf\" \"no\"   # loops\n", MoviePlayerKeys::generate($m), 'written back as IINA writes it');
same(['IINA Default', 'mpv Default', 'VLC Default', 'Movist Default', 'Movist v2 Default'], array_slice(MoviePlayerKeys::configNames(), 0, 5), 'IINA\'s sets first');
$set = new PlayerSettings(sys_get_temp_dir() . '/myphp-keys-' . getmypid() . '.json');
$current = MoviePlayerKeys::current($set);
check(count($current) > 50 && in_array('Meta+s', array_column($current, 'normal'), true), 'the set the settings name: IINA\'s default, its bindings (' . count($current) . ')');
$set->set('currentInputConfigName', 'gone');
same(count($current), count(MoviePlayerKeys::current($set)), 'a set gone: IINA\'s default instead');
@unlink(sys_get_temp_dir() . '/myphp-keys-' . getmypid() . '.json');
